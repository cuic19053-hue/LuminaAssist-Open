<#
.SYNOPSIS
  光语助手端侧模型资产下载脚本（P0-3 配套）
.DESCRIPTION
  1. 下载 MobileNetV2 .ms 模型（华为官方模型库，约 13MB）；
  2. 下载 ImageNet 1001 类英文标签（keras-vis 仓库）；
  3. 自动生成 imagenet_labels.json（zh/en 格式，英文为主，常见类别含中文）；
  4. 放置到 entry/src/main/resources/rawfile/models/ 目录。
.NOTES
  执行：pwsh setup_models.ps1  或  powershell -File setup_models.ps1
  模型来源：https://download.mindspore.cn/model_zoo/official/lite/mobilenetv2_openimage_lite/1.5/mobilenetv2.ms
#>

param(
    [string]$ProjectRoot = "d:\c4.ai.huawei\LuminaApp"
)

$ErrorActionPreference = "Stop"
$rawfileDir = Join-Path $ProjectRoot "entry\src\main\resources\rawfile\models"

# 1) 创建目标目录
if (-not (Test-Path $rawfileDir)) {
    New-Item -ItemType Directory -Path $rawfileDir -Force | Out-Null
    Write-Host "已创建目录: $rawfileDir" -ForegroundColor Green
}

# 2) 下载 MobileNetV2 模型（华为官方）
$modelUrl = "https://download.mindspore.cn/model_zoo/official/lite/mobilenetv2_openimage_lite/1.5/mobilenetv2.ms"
$modelPath = Join-Path $rawfileDir "mobilenetv2.ms"

if (Test-Path $modelPath) {
    $size = (Get-Item $modelPath).Length
    if ($size -gt 1MB) {
        Write-Host "MobileNetV2 模型已存在 ($('{0:N2}' -f ($size/1MB)) MB)，跳过下载" -ForegroundColor Yellow
    } else {
        Write-Host "MobileNetV2 模型文件异常，重新下载..." -ForegroundColor Yellow
        Remove-Item $modelPath -Force
    }
}

if (-not (Test-Path $modelPath)) {
    Write-Host "正在下载 MobileNetV2 模型（~13MB）..." -ForegroundColor Cyan
    try {
        Invoke-WebRequest -Uri $modelUrl -OutFile $modelPath -UseBasicParsing -TimeoutSec 120
        $size = (Get-Item $modelPath).Length
        Write-Host "MobileNetV2 模型下载完成: $('{0:N2}' -f ($size/1MB)) MB" -ForegroundColor Green
    } catch {
        Write-Host "下载失败：$($_.Exception.Message)" -ForegroundColor Red
        Write-Host "请手动下载：$modelUrl" -ForegroundColor Yellow
        Write-Host "并放置到：$modelPath" -ForegroundColor Yellow
        exit 1
    }
}

# 3) 下载 ImageNet 1001 类标签（keras-vis 仓库）
$labelsUrl = "https://raw.githubusercontent.com/raghakot/keras-vis/master/resources/imagenet_class_index.json"
$labelsTempPath = Join-Path $env:TEMP "imagenet_class_index.json"

Write-Host "正在下载 ImageNet 1001 类标签..." -ForegroundColor Cyan
try {
    Invoke-WebRequest -Uri $labelsUrl -OutFile $labelsTempPath -UseBasicParsing -TimeoutSec 60
    Write-Host "ImageNet 标签下载完成" -ForegroundColor Green
} catch {
    Write-Host "ImageNet 标签下载失败：$($_.Exception.Message)" -ForegroundColor Red
    Write-Host "将使用简化版标签" -ForegroundColor Yellow
    $labelsTempPath = $null
}

# 4) 转换为 {zh, en} 格式
