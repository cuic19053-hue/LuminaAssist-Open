import os

target = r'd:\c4.ai.huawei\LuminaApp\entry\src\main\ets\utils\AccessibilityUtils.ets'

lines = []
lines.append('/**')
lines.append(' * @file AccessibilityUtils.ets')
lines.append(' * @module utils')
lines.append(' * @description 无障碍能力工具类（TTS 委托给 SpeechService，振动兜底）。')
lines.append(' *')
lines.append(' * 职责：')
lines.append(' * 1. TTS 播报（委托给 SpeechService，主语音通道）；')
lines.append(' * 2. 焦点提示（辅助通道）；')
lines.append(' * 3. 触觉反馈降级（TTS 不可用时使用振动）。')
lines.append(' *')
lines.append(' * 设计原则：')
lines.append(' * - VUI 优先：视障用户从语音获取一切信息；')
lines.append(' * - 错误兜底：TTS 失败时记录日志并尝试振动，禁止"无声失败"（铁律 3）。')
lines.append(' *')
lines.append(' * 架构（端云双态 - 铁律 1）：')
lines.append(' * - 本类不持有 API Key，仅作为 SpeechService 的统一调用入口；')
lines.append(' * - SpeechService 由 EntryAbility 注入 context + API Key（KeyStore 加密）；')
lines.append(' * - SpeechService 未就绪时本类自动降级为振动反馈。')
lines.append(' */')
lines.append('')
lines.append("import vibrator from '@ohos.vibrator';")
lines.append("import { Logger } from './Logger';")
lines.append("import { SpeechService } from '../services/SpeechService';")
lines.append('')
lines.append("const TAG: string = 'AccessibilityUtils';")
lines.append('')
lines.append('/**')
lines.append(' * AccessibilityUtils —— 无障碍能力工具类（单例）。')
lines.append(' */')
lines.append('export class AccessibilityUtils {')
lines.append('  private static instance: AccessibilityUtils | null = null;')
lines.append('')
lines.append('  private constructor() {')
lines.append('  }')
lines.append('')
lines.append('  public static getInstance(): AccessibilityUtils {')
lines.append('    if (AccessibilityUtils.instance === null) {')
lines.append('      AccessibilityUtils.instance = new AccessibilityUtils();')
lines.append('    }')
lines.append('    return AccessibilityUtils.instance;')
lines.append('  }')
lines.append('')
lines.append('  /**')
lines.append('   * 初始化 TTS 通道。')
lines.append('   *')
lines.append('   * 本类不创建 TTS 引擎，仅作为 SpeechService 的统一调用入口。')
lines.append('   * SpeechService 由 EntryAbility 在 onCreate 中初始化（注入 context + API Key）。')
lines.append('   * 此方法保留供 EntryAbility 早期调用，记录日志即可。')
lines.append('   */')
lines.append('  public initTTS(): void {')
lines.append('    const ready: boolean = SpeechService.getInstance().isReady();')
lines.append("    Logger.info(TAG, 'initTTS 调用，SpeechService ready=' + String(ready));")
lines.append('  }')
lines.append('')
lines.append('  /**')
lines.append('   * 异步播报。')
lines.append('   *')
lines.append('   * 行为：')
lines.append('   * - 若 SpeechService 已就绪：委托真实 TTS 合成 + AVPlayer 播放；')
lines.append('   * - 若 SpeechService 未就绪 / 播放失败：自动降级为振动反馈，确保视障用户不会"无声失败"。')
lines.append('   *')
lines.append('   * @param message 中文文本')
lines.append('   */')
lines.append('  public async speak(message: string): Promise<void> {')
lines.append('    if (!message || message.length === 0) {')
lines.append('      return;')
lines.append('    }')
lines.append('    const speech = SpeechService.getInstance();')
lines.append('    if (!speech.isReady()) {')
lines.append("      Logger.warn(TAG, 'SpeechService 未就绪，触发振动降级: ' + message);")
lines.append('      await this.vibrateFallback();')
lines.append('      return;')
lines.append('    }')
lines.append('    try {')
lines.append('      await speech.speak(message);')
lines.append('    } catch (error) {')
lines.append('      const msg: string = error instanceof Error ? error.message : JSON.stringify(error);')
lines.append("      Logger.error(TAG, 'TTS 播报失败，触发振动降级: ' + msg);")
lines.append('      await this.vibrateFallback();')
lines.append('    }')
lines.append('  }')
lines.append('')
lines.append('  /**')
lines.append('   * 停止当前播报。')
lines.append('   */')
lines.append('  public stopSpeak(): void {')
lines.append('    try {')
lines.append('      SpeechService.getInstance().stopSpeak();')
lines.append('    } catch (error) {')
lines.append("      Logger.error(TAG, '停止播报失败: ' + JSON.stringify(error));")
lines.append('    }')
lines.append('  }')
lines.append('')
lines.append('  /**')
lines.append('   * 振动降级（TTS 不可用时的兜底反馈）。')
lines.append('   */')
lines.append('  private async vibrateFallback(): Promise<void> {')
lines.append('    try {')
lines.append("      vibrator.startVibration({ type: 'time', duration: 200 }, { id: 0, usage: 'touch' });")
lines.append('    } catch (error) {')
lines.append("      Logger.error(TAG, '振动降级失败: ' + JSON.stringify(error));")
lines.append('    }')
lines.append('  }')
lines.append('')
lines.append('  /**')
lines.append('   * 释放资源（委托给 SpeechService）。')
lines.append('   */')
lines.append('  public destroy(): void {')
lines.append('    try {')
lines.append('      SpeechService.getInstance().destroy();')
lines.append('    } catch (error) {')
lines.append("      Logger.error(TAG, 'SpeechService 销毁失败: ' + JSON.stringify(error));")
lines.append('    }')
lines.append('  }')
lines.append('}')
lines.append('')

content = '\n'.join(lines)
with open(target, 'w', encoding='utf-8') as f:
    f.write(content)

print('WRITTEN', target, 'LEN', len(content))
